const grid =
  document.getElementById("credentialGrid");

const emptyState =
  document.getElementById("emptyState");

const searchInput =
  document.getElementById("searchInput");

const credentialCount =
  document.getElementById("credentialCount");

const filters =
  document.querySelectorAll(".filter");


let activeFilter = "all";


const typeLabels = {

  certification:
    "Certification",

  course:
    "Course",

  competition:
    "Competition",

  internship:
    "Internship"

};


function escapeHtml(value) {

  return String(value)

    .replaceAll("&", "&amp;")

    .replaceAll("<", "&lt;")

    .replaceAll(">", "&gt;")

    .replaceAll('"', "&quot;")

    .replaceAll("'", "&#039;");

}


function renderCredentials() {

  const query =
    searchInput.value
      .trim()
      .toLowerCase();


  const visibleCredentials =
    credentials.filter((credential) => {

      const matchesFilter =
        activeFilter === "all" ||
        credential.type === activeFilter;


      const searchableText = [

        credential.title,

        credential.issuer,

        credential.date,

        credential.id,

        credential.description,

        ...credential.skills

      ]
        .join(" ")
        .toLowerCase();


      const matchesSearch =
        searchableText.includes(query);


      return matchesFilter && matchesSearch;

    });


  credentialCount.textContent =
    credentials.length;


  grid.innerHTML = "";


  visibleCredentials.forEach(
    (credential, index) => {

      const card =
        document.createElement("article");


      card.className = "card";


      card.style.animationDelay =
        `${Math.min(index * 45, 500)}ms`;


      const skills =
        credential.skills.length > 0

          ? `
            <div class="skills">

              ${credential.skills
                .map(
                  (skill) =>
                    `<span class="skill">
                      ${escapeHtml(skill)}
                    </span>`
                )
                .join("")}

            </div>
          `

          : "";


      const description =
        credential.description

          ? `
            <p class="description">
              ${escapeHtml(credential.description)}
            </p>
          `

          : "";


      const credentialId =
        credential.id

          ? `
            <span class="credential-id">
              ID · ${escapeHtml(credential.id)}
            </span>
          `

          : `
            <span class="credential-id">
              Credential details coming soon
            </span>
          `;


      card.innerHTML = `

        <div class="card-top">

          <div class="logo">
            ${escapeHtml(credential.logo)}
          </div>

          <span class="type">
            ${escapeHtml(
              typeLabels[credential.type]
            )}
          </span>

        </div>


        <h2>
          ${escapeHtml(credential.title)}
        </h2>


        <p class="issuer">
          ${escapeHtml(credential.issuer)}
        </p>


        <p class="date">
          ${escapeHtml(credential.date)}
        </p>


        ${description}

        ${skills}


        <div class="card-bottom">

          ${credentialId}


          <a
            class="view-link"
            href="${escapeHtml(
              credential.credentialUrl
            )}"
            target="_blank"
            rel="noopener noreferrer"
          >
            View Credential

            <span class="view-link-arrow">
              ↗
            </span>
          </a>

        </div>

      `;


      grid.appendChild(card);

    }
  );


  emptyState.hidden =
    visibleCredentials.length !== 0;

}


filters.forEach((button) => {

  button.addEventListener(
    "click",
    () => {

      filters.forEach(
        (item) =>
          item.classList.remove("active")
      );


      button.classList.add("active");


      activeFilter =
        button.dataset.filter;


      renderCredentials();

    }
  );

});


searchInput.addEventListener(
  "input",
  renderCredentials
);


renderCredentials();
